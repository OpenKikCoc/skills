#!/usr/bin/env python3
"""
Bundle the deck shell + its slide files into ONE self-contained HTML file.

    python3 build-single-file.py [output.html]

The shell (index.html, or deck-shell.html if no index.html exists in this
directory) carries one empty <iframe class="slide"> per slide, in SLIDES
order -- opened directly, those iframes load the slide files by URL. This
script fills each tag's `data-doc` attribute with that slide's whole
document, so the bundle needs no sibling files and survives being mailed,
uploaded, or opened from Downloads.

Each slide stays a separate document on purpose: slides reuse the same
element ids (#stage, #next-step, ...), the same global `const STEPS`, the
same SVG <marker> ids, and conflicting `:root` variables, so merging them
into one document breaks them. See reference/conventions.md.

Edit the shell and the slide files as usual, then re-run this.
"""

import pathlib
import re
import sys

HERE = pathlib.Path(__file__).resolve().parent
SHELL_CANDIDATES = [HERE / "index.html", HERE / "deck-shell.html"]
DEFAULT_OUT = HERE / "deck.html"

# Anchored on the slide iframes so a `data-doc` mentioned in a comment is ignored.
IFRAME = re.compile(r'<iframe class="slide"[^>]*?></iframe>')

BANNER = (
    "<!--\n"
    "  Single-file build of this deck.\n"
    "  Generated by build-single-file.py -- edit the shell and the slide\n"
    "  source files, then re-run it to regenerate this file.\n"
    "-->\n\n"
)


def esc_attr(s: str) -> str:
    """Escape for a double-quoted HTML attribute. `<` and `>` are legal inside
    an attribute value, so leaving them alone keeps the payload readable."""
    return s.replace("&", "&amp;").replace('"', "&quot;")


def main() -> int:
    out = pathlib.Path(sys.argv[1]) if len(sys.argv) > 1 else DEFAULT_OUT

    shell_path = next((p for p in SHELL_CANDIDATES if p.exists()), None)
    if shell_path is None:
        names = " or ".join(p.name for p in SHELL_CANDIDATES)
        print(f"error: no shell found ({names})", file=sys.stderr)
        return 1
    shell = shell_path.read_text(encoding="utf-8")

    files = re.findall(r"file: '([^']+)'", shell)
    tags = IFRAME.findall(shell)
    if not files:
        print(f"error: no slide list found in {shell_path.name}", file=sys.stderr)
        return 1
    if len(tags) != len(files):
        print(
            f"error: {shell_path.name} has {len(tags)} slide iframes but "
            f"{len(files)} slides in SLIDES -- they must match 1:1",
            file=sys.stderr,
        )
        return 1

    docs = []
    total = 0
    for name in files:
        p = HERE / name
        if not p.exists():
            print(f"error: missing slide file {name}", file=sys.stderr)
            return 1
        doc = p.read_text(encoding="utf-8")
        total += len(doc)
        docs.append(doc)
        print(f"  + {name:46s} {len(doc)//1024:4d} kB")

    it = iter(docs)

    def fill(m: "re.Match[str]") -> str:
        tag = m.group(0)
        return tag.replace("></iframe>", ' data-doc="%s"></iframe>' % esc_attr(next(it)), 1)

    bundled = IFRAME.sub(fill, shell)
    bundled = bundled.replace("<!DOCTYPE html>\n", "<!DOCTYPE html>\n" + BANNER, 1)

    out.write_text(bundled, encoding="utf-8")
    print(
        f"\n  {out.name}: {len(files)} slides, "
        f"{total//1024} kB of slide HTML -> {len(bundled)//1024} kB total"
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
